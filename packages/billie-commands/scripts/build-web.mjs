// Builds the website's command bar from the shared sources, the same way design tokens are shared:
// the outputs are generated, committed, and checked for freshness by test/webBuild.test.ts.
//
//   public/billie-command.js            the command bar (shared engine + @nlae/react + React), one IIFE
//   public/billie-command.css           its layout and token mapping
//   config/smart_command/web-manifest.json   the web registry for the Rails trusted executor
//
// Run: node packages/billie-commands/scripts/build-web.mjs        (from the repository root)
// Uses the repository's esbuild and the universal client's React, so no new dependencies.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as esbuild from "esbuild";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const packages = join(root, "packages");
const universalModules = join(root, "clients/universal/node_modules");

export const OUTPUTS = {
  js: join(root, "public/billie-command.js"),
  css: join(root, "public/billie-command.css"),
  manifest: join(root, "config/smart_command/web-manifest.json"),
};

const alias = {
  "@billie/commands": join(packages, "billie-commands/src/index.ts"),
  "@billie/shared-types": join(packages, "shared-types/src/index.ts"),
  "@nlae/core": join(packages, "nl-action-engine/src/index.ts"),
  "@nlae/react/commandBar.css": join(packages, "nl-action-react/src/commandBar.css"),
  "@nlae/react": join(packages, "nl-action-react/src/index.ts"),
  // One React for the whole bundle: the universal client's (the root node_modules has another copy).
  react: join(universalModules, "react"),
  "react-dom": join(universalModules, "react-dom"),
  scheduler: join(universalModules, "scheduler"),
};

const HEADER = "/* Generated by packages/billie-commands/scripts/build-web.mjs from packages/billie-commands, packages/nl-action-engine and packages/nl-action-react. Do not edit. */";

/** Builds everything in memory; returns the file contents by output name. */
export async function buildWeb() {
  const bundle = await esbuild.build({
    entryPoints: [join(packages, "billie-commands/src/web/main.tsx")],
    bundle: true,
    write: false,
    outdir: join(root, "public"),
    entryNames: "billie-command",
    format: "iife",
    platform: "browser",
    target: ["es2020", "safari15", "chrome105", "firefox110"],
    minify: true,
    jsx: "automatic",
    legalComments: "eof",
    charset: "utf8",
    alias,
    define: { "process.env.NODE_ENV": '"production"' },
    banner: { js: HEADER, css: HEADER },
    logLevel: "silent",
  });
  const files = Object.fromEntries(bundle.outputFiles.map((file) => [file.path.endsWith(".css") ? "css" : "js", file.text]));

  // The manifest comes from the same registry the bundle parses with.
  const probe = await esbuild.build({
    stdin: { contents: 'import { webRegistry } from "@billie/commands"; export default webRegistry().manifest();', resolveDir: root, loader: "ts" },
    bundle: true, write: false, format: "esm", platform: "node", alias, logLevel: "silent",
  });
  const { default: manifest } = await import(`data:text/javascript;base64,${Buffer.from(probe.outputFiles[0].text).toString("base64")}`);
  files.manifest = `${JSON.stringify(manifest, null, 2)}\n`;
  return files;
}

/** Which committed outputs differ from a fresh build (empty when up to date). */
export async function staleOutputs() {
  const fresh = await buildWeb();
  return Object.keys(OUTPUTS).filter((name) => {
    try {
      return readFileSync(OUTPUTS[name], "utf8") !== fresh[name];
    } catch {
      return true;
    }
  });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const files = await buildWeb();
  for (const [name, path] of Object.entries(OUTPUTS)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, files[name]);
    console.log(`${path.replace(root, "")}  ${(Buffer.byteLength(files[name]) / 1024).toFixed(1)} KB`);
  }
}
