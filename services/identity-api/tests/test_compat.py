RAILS = os.environ.get("IDENTITY_RAILS_COMPAT") == "1"


@pytest.mark.skipif(not RAILS, reason="set IDENTITY_RAILS_COMPAT=1 (needs Ruby, the Rails app and the full Rails schema)")
def test_rails_accepts_and_signs_in_python_created_accounts(client, make_client, mail, sql, rails_full_schema, database_url, tmp_path):
    assert rails_full_schema, "load the full Rails schema into the test database first (see README)"
    from test_google import CLIENT_ID, AppFlow, FakeGoogle, signed_in_to_google  # noqa: PLC0415
    import httpx  # noqa: PLC0415
    from identity_api.google import GoogleClient  # noqa: PLC0415

    # 1. Email/password account, 2. Unicode password + nickname + region.
    accounts = []
    for email, password, region in (("compat-one@example.org", "a unique passphrase", "JP"), ("compat-two@example.org", "密码 pässwörd 🙂 long", "XG")):
        started = client.post("/v1/registrations", json={**VALID, "email": email, "password": password, "password_confirmation": password, "usage_region": region}).json()
        assert client.post(f"/v1/registrations/{started['registration_id']}/confirmation",
                           json={"registration_secret": started["registration_secret"], "code": code_from(mail)}).status_code == 201
        accounts.append({"email": email, "password": password})
    # 3. Google account (with its app password).
    google = FakeGoogle()
    gclient = make_client(google_client=GoogleClient(CLIENT_ID, "s", "http://identity.test/v1/google/callback", http=httpx.Client(transport=httpx.MockTransport(google.handler))))
    flow = AppFlow(gclient)
    signed_in_to_google(google, flow, email="compat-google@example.org")
    assert flow.post("complete", password="google app pass", password_confirmation="google app pass", usage_region="US", nickname="Gigi").status_code == 201
    accounts.append({"email": "compat-google@example.org", "password": "google app pass"})
    # 4. EMAIL_VERIFICATION_REQUIRED=false: created at once (unverified address), must sign in like the others.
    bypass = make_client(email_verification_required=False)
    created = bypass.post("/v1/registrations", json={**VALID, "email": "compat-jyun@example.org", "nickname": "Jyun", "usage_region": "XG"})
    assert created.status_code == 201 and created.json()["email_verified"] is False
    accounts.append({"email": "compat-jyun@example.org", "password": VALID["password"]})

    payload = tmp_path / "input.json"
    payload.write_text(json.dumps({"accounts": accounts, "rails_reference_email": "rails-made@example.org", "rails_reference_password": "rails password 1"}))
    env = {**os.environ, "RAILS_ENV": "test", "DATABASE_URL": database_url}
    run = subprocess.run(["mise", "exec", "--", "bin/rails", "runner", str(Path(__file__).parent / "rails/compat_check.rb"), str(payload)],
                         cwd=REPO, env=env, capture_output=True, text=True, timeout=300)
    marker = [line for line in run.stdout.splitlines() if line.startswith("COMPAT_JSON:")]
    assert marker, run.stdout[-2000:] + run.stderr[-2000:]
    report = json.loads(marker[0].removeprefix("COMPAT_JSON:"))
    for result in report["results"]:
        assert result["found"] and result["valid"], result
        assert result["valid_password"] and result["wrong_password_rejected"] and result["active_for_authentication"], result
        assert (result["teams"], result["current_team_name"], result["admin"], result["membership_email"]) == (1, "Your Team", True, result["email"])
        assert result["needs_usage_region"] is False and result["badges"] == ["member"]
        # 10. Login after registration through the EXISTING client endpoint (email is upper-cased in the request).
        assert result["login_status"] == 201 and result["token_authenticates"], result
        assert result["login_owner_id"] == result["db_owner_id"] and result["account_endpoint_email"] == result["email"]
        assert (result["logout_status"], result["relogin_status"]) == (204, 201), result  # sign out, then back in
    assert report["results"][2]["google_uid"] == "1098765"
    assert report["results"][3]["account_endpoint_nickname"] == "Jyun"

    # 9. Existing Rails accounts: duplicates are recognized and their Devise password links Google.
    mail.sent.clear()
    again = client.post("/v1/registrations", json={**VALID, "email": "Rails-Made@example.org"})
    assert again.status_code == 202 and mail.sent[-1].kind == "existing_account"
    google.claims = {}
    flow = AppFlow(gclient)
    google.claims = {"nonce": flow.query["nonce"], "sub": "rails-google-sub", "email": "rails-made@example.org"}
    flow.google_returns(code="c")
    assert flow.post("status").json()["outcome"] == "link_required"
    assert flow.post("link", password="rails password 1").json() == {"status": "linked", "email": "rails-made@example.org"}
