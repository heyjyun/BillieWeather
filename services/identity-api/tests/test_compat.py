REPO = Path(__file__).resolve().parents[3]
RAILS_REGIONS = REPO / "app/models/usage_region.rb"


@pytest.mark.skipif(not RAILS_REGIONS.exists(), reason="Rails app not present")
def test_region_list_matches_rails():
    source = RAILS_REGIONS.read_text()
    block = re.search(r"STANDARD_CODES = %w\[(.*?)\]", source, re.S).group(1)
    assert set(block.split()) == set(regions.STANDARD_CODES)
    assert re.search(r'GLOBAL_CITIZEN_CODE = "(\w+)"', source).group(1) == regions.GLOBAL_CITIZEN_CODE


def test_region_list_matches_the_database_check_constraint(db, sql):
    definition = sql.execute("SELECT pg_get_constraintdef(oid) AS d FROM pg_constraint WHERE conname = 'users_usage_region_allowed'").fetchone()["d"]
    assert set(re.findall(r"'([A-Z]{2})'", definition)) == set(regions.CODES)


def test_schema_check_passes_and_detects_drift(db, sql):
    assert compatibility_problems(sql) == []
    sql.execute("BEGIN")
    try:
        sql.execute("ALTER TABLE public.users RENAME COLUMN usage_region_pending TO usage_region_pending_x")
        assert "missing column users.usage_region_pending" in compatibility_problems(sql)
    finally:
        sql.execute("ROLLBACK")


def test_devise_password_format():
    encrypted = hash_password("pässwörd 🙂", 11)
    assert re.fullmatch(r"\$2a\$11\$[./A-Za-z0-9]{53}", encrypted)
    assert verify_password("pässwörd 🙂", encrypted) and not verify_password("passwörd 🙂", encrypted)
    # Ruby's bcrypt (and so Devise) uses only the first 72 bytes; so does this service.
    long = "x" * 72
    assert verify_password(long + "anything", hash_password(long + "else", 4))
    # Hashes generated by Ruby's bcrypt 3.1.22 (BCrypt::Password.create(..., cost: 11)), the gem Devise uses here.
    assert verify_password("correct horse 42", "$2a$11$iNFMN.DCWG5cIoaoXpsh.Oq.rZj5556IWvfrQUvJAe2T2NnlStby.")
    assert verify_password("密码测试🙂ok", "$2a$11$XbQE8BiUJYj2BLGHIUjj6OmjV9sICOMDno8lGTguhy.3ifu9m6ApO")
    assert not verify_password("correct horse 43", "$2a$11$iNFMN.DCWG5cIoaoXpsh.Oq.rZj5556IWvfrQUvJAe2T2NnlStby.")
    assert verify_password("anything", "not-a-bcrypt-hash") is False and verify_password("x", "") is False


