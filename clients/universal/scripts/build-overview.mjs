// Rails serves the same dashboard and Accounts & Assets components as Tauri, following the command bar's
// committed-bundle convention. Each entry writes public/<name>.js and public/<name>.css.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../../", import.meta.url));
const bundles = [
  ["clients/universal/web/overview.tsx", "public/financial-overview.js", "src/overview/overview.css"],
  ["clients/universal/web/accounts.tsx", "public/accounts-table.js", "src/accounts/accounts.css"],
];
for (const [entry, outfile, css] of bundles) await build({
  absWorkingDir: root,
  entryPoints: [entry],
  bundle: true,
  minify: true,
  outfile,
  jsx: "automatic",
  target: ["safari15", "chrome105"],
  legalComments: "eof",
  alias: {
    "@billie/finance-core": "./packages/finance-core/src/index.ts",
    "@billie/shared-types": "./packages/shared-types/src/index.ts",
    "@billie/design-tokens": "./packages/design-tokens/src/tokens.ts",
    react: "./clients/universal/node_modules/react",
    "react-dom": "./clients/universal/node_modules/react-dom",
  },
  banner: {
    js: "/* Generated by clients/universal/scripts/build-overview.mjs */",
    css: `/* Generated from ${css} */`,
  },
  define: { "process.env.NODE_ENV": '"production"' },
});
