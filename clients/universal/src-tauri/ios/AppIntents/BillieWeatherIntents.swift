// Siri and Shortcuts for BillieWeather (iOS 16+). Each intent only OPENS the app on one screen
// through the app's own URL scheme; it carries no financial data, reads nothing and saves nothing.
// The person then scans, reviews and confirms in the app as usual.
//
//   billieweather://capture/receipt  -> receipt capture (camera / upload)
//   billieweather://capture/expense  -> the manual entry form (new expense)
//   billieweather://open             -> the app
//
// The links are handled by tauri-plugin-deep-link (Cargo.toml, tauri.conf.json `plugins.deep-link`)
// and routed by src/services/deepLink.ts. See README.md in this folder for adding this file to the
// Xcode project generated by `npm run ios:init`.
import AppIntents
import Foundation
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

/// The screens a shortcut may open. Must stay in step with DEEP_LINK_ROUTES in src/services/deepLink.ts.
@available(iOS 16.0, macOS 13.0, *)
enum BillieWeatherLink: String, Sendable {
    case captureReceipt = "capture/receipt"
    case captureExpense = "capture/expense"
    case open = "open"

    var url: URL { URL(string: "billieweather://\(rawValue)")! }

    /// Hands the link to the app's own URL handler (the deep-link plugin). The intent has already
    /// brought the app to the foreground (`openAppWhenRun`).
    @MainActor
    func openInApp() async {
        #if canImport(UIKit)
        _ = await UIApplication.shared.open(url)
        #elseif canImport(AppKit)
        NSWorkspace.shared.open(url)
        #endif
    }
}

@available(iOS 16.0, macOS 13.0, *)
struct ScanReceiptIntent: AppIntent {
    static let title: LocalizedStringResource = "Scan a receipt with BillieWeather"
    static let description = IntentDescription("Opens BillieWeather on the receipt camera. The receipt is read on your device and nothing is saved until you confirm.")
    static let openAppWhenRun = true

    @MainActor
    func perform() async throws -> some IntentResult {
        await BillieWeatherLink.captureReceipt.openInApp()
        return .result()
    }
}

@available(iOS 16.0, macOS 13.0, *)
struct AddExpenseIntent: AppIntent {
    static let title: LocalizedStringResource = "Add an expense to BillieWeather"
    static let description = IntentDescription("Opens the new expense form in BillieWeather.")
    static let openAppWhenRun = true

    @MainActor
    func perform() async throws -> some IntentResult {
        await BillieWeatherLink.captureExpense.openInApp()
        return .result()
    }
}

@available(iOS 16.0, macOS 13.0, *)
struct OpenBillieWeatherIntent: AppIntent {
    static let title: LocalizedStringResource = "Open BillieWeather"
    static let description = IntentDescription("Opens BillieWeather.")
    static let openAppWhenRun = true

    @MainActor
    func perform() async throws -> some IntentResult {
        await BillieWeatherLink.open.openInApp()
        return .result()
    }
}

/// iOS 18+: the same screens through the system's OpenURLIntent, which opens the link without
/// first running code in the app. Optional; the intents above work from iOS 16.
@available(iOS 18.0, macOS 15.0, *)
struct ScanReceiptByLinkIntent: AppIntent {
    static let title: LocalizedStringResource = "Scan a receipt with BillieWeather (link)"
    static let isDiscoverable = false

    func perform() async throws -> some IntentResult & OpensIntent {
        .result(opensIntent: OpenURLIntent(BillieWeatherLink.captureReceipt.url))
    }
}

/// The phrases Siri and the Shortcuts app offer without any setup. Every phrase names the app.
/// (`shortTitle` / `systemImageName` need iOS 16.4; on 16.0–16.3 the intents are still listed in
/// the Shortcuts app, without these ready-made phrases.)
@available(iOS 16.4, macOS 13.3, *)
struct BillieWeatherShortcuts: AppShortcutsProvider {
    static var appShortcuts: [AppShortcut] {
        AppShortcut(intent: ScanReceiptIntent(), phrases: [
            "Scan a receipt with \(.applicationName)",
            "Scan receipt in \(.applicationName)",
            "Add a receipt to \(.applicationName)",
        ], shortTitle: "Scan Receipt", systemImageName: "doc.text.viewfinder")
        AppShortcut(intent: AddExpenseIntent(), phrases: [
            "Add an expense to \(.applicationName)",
            "Record an expense in \(.applicationName)",
        ], shortTitle: "Add Expense", systemImageName: "plus.circle")
        AppShortcut(intent: OpenBillieWeatherIntent(), phrases: [
            "Open \(.applicationName)",
        ], shortTitle: "Open BillieWeather", systemImageName: "app")
    }
}
