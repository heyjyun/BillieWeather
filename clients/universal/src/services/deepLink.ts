// billieweather:// links: Siri / Shortcuts App Intents (src-tauri/ios/AppIntents) and the URL
// scheme open one screen of the app. A link only ever names a screen from the allowlist below;
// it never carries data (query strings and anything else are ignored), and it never saves,
// sends or changes anything by itself. The person still does every step on the screen.
//
// Sources, all funnelled into the same routes:
// - Tauri's deep-link plugin (installed apps): the link that launched the app (getCurrent) and
//   links opened while it runs (onOpenUrl). `plugins.deep-link` in tauri.conf.json registers the
//   scheme (iOS/Android Info.plist / manifest are generated by the plugin's build step).
// - The location hash, `#/capture/receipt`, so the same routes work in a browser and in tests.
import { isTauri } from "./platform";

export const DEEP_LINK_SCHEME = "billieweather";
export const DEEP_LINK_ROUTES = ["capture/receipt", "capture/expense", "open"] as const;
export type DeepLinkRoute = (typeof DEEP_LINK_ROUTES)[number];

const isRoute = (value: string): value is DeepLinkRoute => (DEEP_LINK_ROUTES as readonly string[]).includes(value);
const clean = (path: string) => path.replace(/^\/+|\/+$/g, "").toLowerCase();

/** `billieweather://capture/receipt`, `billieweather:///capture/receipt`, `billieweather:open` → route; anything else → null. */
export function routeFromUrl(url: string): DeepLinkRoute | null {
  const match = /^([a-z][a-z0-9+.-]*):(?:\/\/)?([^?#]*)/i.exec(url.trim());
  if (!match || match[1].toLowerCase() !== DEEP_LINK_SCHEME) return null;
  const path = clean(match[2]);
  if (path === "") return "open";
  return isRoute(path) ? path : null;
}

/** `#/capture/receipt` or `#capture/receipt` → route. */
export function routeFromHash(hash: string): DeepLinkRoute | null {
  const path = clean(hash.replace(/^#/, "").split("?")[0]);
  return path !== "" && isRoute(path) ? path : null;
}

type Listener = (route: DeepLinkRoute) => void;
const listeners = new Set<Listener>();
let pending: DeepLinkRoute | null = null;
let started: Promise<void> | null = null;

function deliver(route: DeepLinkRoute | null) {
  if (!route) return;
  if (listeners.size === 0) {
    pending = route; // the app is not ready yet (signing in, opening the database): keep the latest
    return;
  }
  for (const listener of listeners) listener(route);
}

function consumeHash() {
  if (typeof window === "undefined") return;
  const route = routeFromHash(window.location.hash);
  if (!route) return;
  // Clear it, so the same link can be opened again and a reload does not repeat it.
  try {
    window.history.replaceState(null, "", window.location.pathname + window.location.search);
  } catch {
    window.location.hash = "";
  }
  deliver(route);
}

/** Starts listening once (idempotent). Safe without Tauri: the plugin is only loaded inside the app. */
export function startDeepLinks(): Promise<void> {
  started ??= (async () => {
    if (typeof window === "undefined") return;
    window.addEventListener("hashchange", consumeHash);
    consumeHash();
    if (!isTauri()) return;
    try {
      const plugin = await import("@tauri-apps/plugin-deep-link");
      for (const url of (await plugin.getCurrent()) ?? []) deliver(routeFromUrl(url));
      await plugin.onOpenUrl((urls) => { for (const url of urls) deliver(routeFromUrl(url)); });
    } catch {
      // The plugin is missing on this build: links are not available, everything else works.
    }
  })();
  return started;
}

/** Calls `listener` for every link; a link that arrived before anyone listened is delivered now. */
export function subscribeDeepLinks(listener: Listener): () => void {
  listeners.add(listener);
  void startDeepLinks();
  consumeHash(); // a hash set before the app was ready
  if (pending) {
    const route = pending;
    pending = null;
    listener(route);
  }
  return () => { listeners.delete(listener); };
}

/** Tests only. */
export function resetDeepLinksForTests(): void {
  listeners.clear();
  pending = null;
  if (typeof window !== "undefined") window.removeEventListener("hashchange", consumeHash);
  started = null;
}
